const DICTS: Record<Lang, Dict> = { en, th, ja, my, km, lo };

/** Locale tags for dates (month / weekday names). */
export const LOCALES: Record<Lang, string> = { en: 'en-US', th: 'th-TH', ja: 'ja-JP', my: 'my-MM', km: 'km-KH', lo: 'lo-LA' };

export type Params = Record<string, string | number>;
export type TFunction = (key: string, params?: Params) => string;

export function translate(lang: Lang, key: string, params?: Params): string {
  const raw =
    EXTRA[lang][key] ??
    (DICTS[lang] as Record<string, string | undefined>)[key] ??
    EXTRA.en[key] ??
    (en as Record<string, string>)[key] ??
    key;
  return params ? raw.replace(/\{(\w+)\}/g, (_, p: string) => String(params[p] ?? `{${p}}`)) : raw;
}

/** "Machine 01" → "เครื่อง 01" / "機械01" … */
export const machineName = (t: TFunction, label?: string) => (label ? t('machine', { n: label.replace(/\D+/g, '') }) : '');
/** "Supervisor 01" → "หัวหน้างาน 01" … */
export const groupName = (t: TFunction, group?: string) => (group ? t('group', { n: group.replace(/\D+/g, '') }) : '');
